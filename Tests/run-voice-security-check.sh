#!/bin/bash
# Голосовой ввод: подпись помощника при каждом запуске, запасная вставка не попадает в историю буфера.
# Папка стенда: VOICE_CHECK_DIR, иначе $TMPDIR/voice-security-check.
source "$(dirname "$0")/lib/check-limit.sh"
set -euo pipefail
cd "$(dirname "$0")/.."
OUT="${VOICE_CHECK_DIR:-${TMPDIR:-/tmp}/voice-security-check}"
ENGINE=Sources/Modules/Voice/VoiceEngine.swift
CONTROLLER=Sources/Modules/Voice/VoiceController.swift

fail() { echo "ПРОВАЛ: $1"; exit 1; }

# Чтобы запустить ensureHelper, нужны модель и подписанный помощник, поэтому проверяем по исходнику.
if grep -q 'signatureChecked' "$ENGINE"; then fail "подпись помощника проверяется один раз за жизнь процесса"; fi
BODY="$(awk '/func ensureHelper/,/^    }$/' "$ENGINE")"
VERIFY="$(grep -n 'try Self.verifyHelper(url)' <<<"$BODY" | cut -d: -f1)"
LAUNCH="$(grep -n 'try HelperProcess(executable: url)' <<<"$BODY" | cut -d: -f1)"
[ -n "$VERIFY" ] && [ -n "$LAUNCH" ] && [ "$VERIFY" -lt "$LAUNCH" ] || fail "подпись не проверяется перед запуском помощника"
if grep -B3 'try Self.verifyHelper(url)' "$ENGINE" | grep -q '  if '; then fail "проверка подписи стоит под условием"; fi
grep -q '^actor VoiceEngine' "$ENGINE" || fail "VoiceEngine больше не актор: codesign может попасть на главный поток"
echo "ok   подпись помощника проверяется перед каждым запуском, вне главного потока"

# Обе вставки кладут один и тот же элемент.
if grep -qE 'setString\(text, forType' "$CONTROLLER"; then fail "текст кладётся в буфер без пометок"; fi
[ "$(grep -c 'VoicePasteItem.make(text)' "$CONTROLLER")" = 2 ] || fail "не обе вставки используют VoicePasteItem"
echo "ok   обе вставки используют один элемент буфера"

mkdir -p "$OUT"
cat >"$OUT/main.swift" <<'SWIFT'
import AppKit

let item = VoicePasteItem.make("секрет")
let types = Set(item.types.map(\.rawValue))
guard item.string(forType: .string) == "секрет" else { print("ПРОВАЛ: нет текста"); exit(1) }
guard types.isSuperset(of: ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]) else {
    print("ПРОВАЛ: нет пометок: \(types)")
    exit(1)
}
print("ok   элемент: текст и пометки временной записи")
SWIFT
swiftc -o "$OUT/check" "$OUT/main.swift" Sources/Modules/Voice/VoicePasteItem.swift -framework AppKit
"$OUT/check"

# Именно эти типы отсеивает история буфера.
for type in org.nspasteboard.TransientType org.nspasteboard.AutoGeneratedType; do
  grep -q "$type" Sources/Modules/Clipboard/ClipboardModels.swift || fail "история буфера не отсеивает $type"
done
echo "ok   история буфера отсеивает эти пометки"
