import Foundation
import AppKit
import CryptoKit

// Проверка логики «Буфера» без интерфейса. Запуск: Tests/run-clipboard-check.sh
// Реальный буфер обмена и Keychain пользователя не трогаются: свой NSPasteboard, свой каталог, свой сервис.

var failures = 0
func check(_ ok: Bool, _ name: String) {
    print((ok ? "ok   " : "FAIL ") + name)
    if !ok { failures += 1 }
}

let root = FileManager.default.temporaryDirectory.appendingPathComponent("clipcheck-\(UUID().uuidString)")
defer { try? FileManager.default.removeItem(at: root) }
let dir = root.appendingPathComponent("Clipboard")
let key = SymmetricKey(size: .bits256)

func snap(_ text: String, types: [String] = ["public.utf8-plain-text"]) -> ClipSnapshot {
    ClipSnapshot(types: types, text: text, sourceBundleID: "com.example.app", sourceName: "App")
}

// 1. Скрытые типы пропускаются
do {
    let store = ClipboardStore(directory: dir, key: key)
    check(!store.ingest(snap("secret", types: ["public.utf8-plain-text", "org.nspasteboard.ConcealedType"])), "Concealed пропущен")
    check(!store.ingest(snap("tmp", types: ["org.nspasteboard.TransientType"])), "Transient пропущен")
    check(!store.ingest(snap("auto", types: ["org.nspasteboard.AutoGeneratedType"])), "AutoGenerated пропущен")
    check(store.items.isEmpty, "после скрытых история пуста")
    check(!store.ingest(snap("   \n ")), "пустой текст пропущен")
}

// 2. Повтор поднимается, а не дублируется; ссылки определяются
do {
    let store = ClipboardStore(directory: dir, key: key)
    store.ingest(snap("one"), now: Date(timeIntervalSince1970: 100))
    store.ingest(snap("https://github.com/x/y"), now: Date(timeIntervalSince1970: 200))
    store.ingest(snap("two"), now: Date(timeIntervalSince1970: 300))
    check(store.items.map { $0.text } == ["two", "https://github.com/x/y", "one"], "порядок: новые сверху")
    check(store.items[1].kind == .link && store.items[1].host == "github.com", "ссылка определена, хост github.com")
    store.ingest(snap("one"), now: Date(timeIntervalSince1970: 400))
    check(store.items.count == 3 && store.items[0].text == "one", "повтор поднят наверх без дубля")
    check(store.items[0].date == Date(timeIntervalSince1970: 400), "у поднятой обновлено время")
    check(!ClipboardPolicy.isLink("see https://a.com now"), "текст со ссылкой внутри — не ссылка")
}

// 3. Лимит не трогает закреплённое
do {
    let store = ClipboardStore(directory: dir.appendingPathComponent("limit"), key: key, limit: 10)
    let space = store.addSpace(name: "pass", colorID: "red")
    store.ingest(snap("pinned-old"))
    store.pin(store.items[0].id, to: space.id)
    for i in 0..<30 { store.ingest(snap("item \(i)")) }
    let unpinned = store.items.filter { $0.spaceID == nil }
    check(unpinned.count == 10, "в истории ровно лимит (10), есть \(unpinned.count)")
    check(store.items.contains { $0.text == "pinned-old" }, "закреплённое пережило лимит")
    check(unpinned.first?.text == "item 29" && unpinned.last?.text == "item 20", "остались самые новые")
    store.clearHistory()
    check(store.items.count == 1 && store.items[0].text == "pinned-old", "«Очистить» оставляет закреплённое")
    store.deleteSpace(space.id)
    check(store.items[0].spaceID == nil, "удаление пространства откладывает запись в историю")
}

// 4. Шифрование: запись -> чтение, на диске нет открытого текста, права 0600/0700
do {
    let secretDir = dir.appendingPathComponent("enc")
    let store = ClipboardStore(directory: secretDir, key: key)
    let space = store.addSpace(name: "Ссылки", colorID: "blue")
    store.ingest(snap("очень-секретная-строка-12345"))
    let png = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: 7, pixelsHigh: 5, bitsPerSample: 8, samplesPerPixel: 4,
                               hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0)!
        .representation(using: .png, properties: [:])!
    store.ingest(ClipSnapshot(types: ["public.png"], imagePNG: png, sourceBundleID: "x", sourceName: "x"))
    store.pin(store.items[1].id, to: space.id)

    let files = (try? FileManager.default.contentsOfDirectory(atPath: secretDir.path)) ?? []
    var leaked = false
    for f in files {
        let data = (try? Data(contentsOf: secretDir.appendingPathComponent(f))) ?? Data()
        if data.range(of: Data("очень-секретная-строка".utf8)) != nil || data.range(of: Data("PNG".utf8)) != nil { leaked = true }
    }
    check(!files.isEmpty && !leaked, "на диске нет открытого текста и PNG (\(files.count) файла)")
    let modes = files.compactMap { (try? FileManager.default.attributesOfItem(atPath: secretDir.appendingPathComponent($0).path))?[.posixPermissions] as? Int }
    check(!modes.isEmpty && modes.allSatisfy { $0 == 0o600 }, "файлы с правами 0600")
    let dirMode = (try? FileManager.default.attributesOfItem(atPath: secretDir.path))?[.posixPermissions] as? Int
    check(dirMode == 0o700, "каталог с правами 0700")

    let reopened = ClipboardStore(directory: secretDir, key: key)
    check(reopened.items.count == 2 && reopened.items.contains { $0.text == "очень-секретная-строка-12345" }, "чтение: записи вернулись")
    check(reopened.spaces.first?.name == "Ссылки", "чтение: пространство вернулось")
    let image = reopened.items.first { $0.kind == .image }
    check(image != nil && reopened.imageData(image!) == png, "чтение: картинка расшифровалась байт в байт")
    check(image?.imageWidth == 7 && image?.imageHeight == 5, "размер картинки 7x5 из заголовка")

    let wrong = ClipboardStore(directory: secretDir, key: SymmetricKey(size: .bits256))
    check(wrong.items.isEmpty, "с чужим ключом история не читается")
    let noKey = ClipboardStore(directory: root.appendingPathComponent("nokey"), key: nil)
    check(!noKey.ingest(snap("x")), "без ключа ничего не пишется")
}

// 5. Keychain: свой сервис, ключ создаётся один раз и стабилен
do {
    let kc = ClipboardKeychain(service: "local.utilitumus.clipboard.test-\(UUID().uuidString)", account: "t")
    defer { kc.delete() }
    let a = kc.key(), b = kc.key()
    let same = a != nil && b != nil && a!.withUnsafeBytes { Data($0) } == b!.withUnsafeBytes { Data($0) }
    check(same, "ключ в Keychain создан и читается тем же")
}

// 6. Реальный NSPasteboard (именованный): скрытый тип, текст, файлы, картинка
do {
    let pb = NSPasteboard(name: NSPasteboard.Name("local.utilitumus.clipcheck.\(UUID().uuidString)"))
    defer { pb.releaseGlobally() }
    let hidden = NSPasteboardItem()
    hidden.setString("пароль", forType: .string)
    hidden.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
    pb.clearContents(); pb.writeObjects([hidden])
    let store = ClipboardStore(directory: dir.appendingPathComponent("pb"), key: key)
    check(!store.ingest(ClipboardPasteboard.snapshot(of: pb)), "буфер с ConcealedType не сохраняется")

    pb.clearContents(); pb.setString("https://example.com/a", forType: .string)
    check(store.ingest(ClipboardPasteboard.snapshot(of: pb)) && store.items[0].kind == .link, "обычный текст-ссылка из буфера сохранён")

    pb.clearContents(); pb.writeObjects([URL(fileURLWithPath: "/tmp/demo.txt") as NSURL])
    check(store.ingest(ClipboardPasteboard.snapshot(of: pb)) && store.items[0].kind == .file && store.items[0].filePaths == ["/tmp/demo.txt"], "файл из буфера сохранён по пути")

    let count = pb.changeCount
    ClipboardPasteboard.write(store.items[1], imageData: nil, to: pb)
    check(pb.changeCount != count && pb.string(forType: .string) == "https://example.com/a", "запись в буфер возвращает текст")
}

print(failures == 0 ? "ВСЕ ПРОВЕРКИ ПРОШЛИ" : "ПРОВАЛЕНО: \(failures)")
exit(failures == 0 ? 0 : 1)
