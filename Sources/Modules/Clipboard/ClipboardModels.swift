import Foundation

/// Тип записи в буфере.
enum ClipKind: String, Codable {
    case text, link, image, file

    var title: String {
        switch self {
        case .text: return "Текст"
        case .link: return "Ссылка"
        case .image: return "Картинка"
        case .file: return "Файл"
        }
    }
}

/// Одна запись истории. Содержимое (текст, пути) лежит в зашифрованном индексе, картинка — в своём файле.
struct ClipItem: Codable, Identifiable, Equatable {
    var id: UUID
    /// Хэш содержимого: по нему повтор находит прежнюю запись.
    var hash: String
    var kind: ClipKind
    /// Текст или адрес ссылки.
    var text: String?
    var filePaths: [String]?
    /// Имя зашифрованного файла с PNG.
    var imageFile: String?
    var imageWidth: Int?
    var imageHeight: Int?
    var sourceBundleID: String?
    var sourceName: String?
    var date: Date
    /// Пространство, в которое запись закреплена; nil — только история.
    var spaceID: UUID?

    var host: String? {
        guard kind == .link, let text, let host = URL(string: text)?.host else { return nil }
        return host.hasPrefix("www.") ? String(host.dropFirst(4)) : host
    }
}

/// Именованное цветное пространство. Цвет — id из палитры, сама палитра в интерфейсе.
struct ClipSpace: Codable, Identifiable, Equatable {
    var id: UUID
    var name: String
    var colorID: String
}

/// То, что лежало в буфере в момент опроса. Без AppKit: так логику можно проверить отдельно.
struct ClipSnapshot: Sendable {
    var types: [String] = []
    var text: String?
    var filePaths: [String] = []
    var imagePNG: Data?
    var sourceBundleID: String?
    var sourceName: String?
}

/// Кто был впереди недавно. Опрос видит запись с задержкой: программа могла записать в буфер и тут же уступить место.
struct ClipFrontHistory {
    /// Сколько секунд программа ещё считается источником после ухода с переднего плана.
    static let window: TimeInterval = 2

    private var current: String?
    private var left: [(id: String, at: Date)] = []

    init(current: String? = nil) { self.current = current }

    mutating func activated(_ id: String?, now: Date = Date()) {
        if let current, current != id { left.append((current, now)) }
        current = id
        left.removeAll { now.timeIntervalSince($0.at) > Self.window }
    }

    /// Текущая программа и те, что ушли с переднего плана не раньше `window` секунд назад.
    func sources(now: Date = Date()) -> [String] {
        left.filter { now.timeIntervalSince($0.at) <= Self.window }.map(\.id) + (current.map { [$0] } ?? [])
    }
}

enum ClipboardPolicy {
    /// Типы, которыми менеджеры паролей и сами программы помечают то, что нельзя запоминать.
    static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        // Старые пометки из списка nspasteboard.org.
        "com.agilebits.onepassword",
        "net.antelle.keeweb",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
        "com.typeit4me.clipping",
    ]

    static let defaultExcludedApps: [String] = [
        "com.1password.1password", "com.agilebits.onepassword7", "com.agilebits.onepassword-osx",
        "com.bitwarden.desktop", "com.apple.keychainaccess", "com.apple.Passwords",
        "org.keepassxc.keepassxc", "com.lastpass.LastPass", "in.sinew.Enpass-Desktop",
        "com.dashlane.dashlanephonefinal",
    ]

    /// Предел текста: длиннее — обрезается, чтобы индекс не раздувался.
    static let maxTextLength = 20_000
    /// Предел PNG: больше — картинку не запоминаем.
    static let maxImageBytes = 6 * 1024 * 1024
    /// Предел текста в байтах до счёта символов: один «символ» из тысяч комбинирующих знаков не заставит обходить всё.
    static let maxTextBytes = maxTextLength * 16
    /// Предел TIFF до декодирования. С запасом: снимок экрана 6K в TIFF весит больше 80 МБ и всё равно проходит.
    static let maxTIFFBytes = 256 * 1024 * 1024
    static let maxTIFFPixels = 64_000_000
    static let defaultLimit = 500
    static let limits = [100, 250, 500, 1000]

    static func shouldSkip(types: [String]) -> Bool {
        types.contains { skippedTypes.contains($0) }
    }

    /// Обрезка до `maxTextLength` символов. Символов не больше, чем байт, поэтому обычный текст весь не обходим.
    static func trimmedText(_ text: String) -> String {
        let utf8 = text.utf8
        guard utf8.count > maxTextLength else { return text }
        guard utf8.count > maxTextBytes else { return String(text.prefix(maxTextLength)) }
        var end = utf8.index(utf8.startIndex, offsetBy: maxTextBytes)
        // Граница байтов не должна разрезать символ UTF-8.
        while end > utf8.startIndex, UTF8.isContinuation(utf8[end]) { end = utf8.index(before: end) }
        return String(text[..<end].prefix(maxTextLength))
    }

    static func tiffFits(bytes: Int, width: Int, height: Int) -> Bool {
        guard bytes <= maxTIFFBytes, width > 0, height > 0 else { return false }
        return width <= maxTIFFPixels / height
    }

    /// Одна строка с http(s)/ftp/mailto и хостом — ссылка; всё остальное — обычный текст.
    static func isLink(_ text: String) -> Bool {
        let t = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !t.isEmpty, t.count < 2048, !t.contains(where: { $0.isWhitespace }),
              let url = URL(string: t), let scheme = url.scheme?.lowercased() else { return false }
        if scheme == "mailto" { return true }
        return ["http", "https", "ftp"].contains(scheme) && (url.host?.isEmpty == false)
    }
}
