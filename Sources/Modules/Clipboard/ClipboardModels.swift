import Foundation

/// Тип записи в буфере.
enum ClipKind: String, Codable {
    case text, link, image, file

    var title: String {
        switch self {
        case .text: return "Текст"
        case .link: return "Ссылка"
        case .image: return "Картинка"
        case .file: return "Файл"
        }
    }
}

/// Одна запись истории. Содержимое (текст, пути) лежит в зашифрованном индексе, картинка — в своём файле.
struct ClipItem: Codable, Identifiable, Equatable {
    var id: UUID
    /// Хэш содержимого: по нему повтор находит прежнюю запись.
    var hash: String
    var kind: ClipKind
    /// Текст или адрес ссылки.
    var text: String?
    var filePaths: [String]?
    /// Имя зашифрованного файла с PNG.
    var imageFile: String?
    var imageWidth: Int?
    var imageHeight: Int?
    var sourceBundleID: String?
    var sourceName: String?
    var date: Date
    /// Пространство, в которое запись закреплена; nil — только история.
    var spaceID: UUID?

    var host: String? {
        guard kind == .link, let text, let host = URL(string: text)?.host else { return nil }
        return host.hasPrefix("www.") ? String(host.dropFirst(4)) : host
    }
}

/// Именованное цветное пространство. Цвет — id из палитры, сама палитра в интерфейсе.
struct ClipSpace: Codable, Identifiable, Equatable {
    var id: UUID
    var name: String
    var colorID: String
}

/// То, что лежало в буфере в момент опроса. Без AppKit: так логику можно проверить отдельно.
struct ClipSnapshot {
    var types: [String] = []
    var text: String?
    var filePaths: [String] = []
    var imagePNG: Data?
    var sourceBundleID: String?
    var sourceName: String?
}

enum ClipboardPolicy {
    /// Типы, которыми менеджеры паролей и сами программы помечают то, что нельзя запоминать.
    static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]

    static let defaultExcludedApps: [String] = [
        "com.1password.1password", "com.agilebits.onepassword7", "com.agilebits.onepassword-osx",
        "com.bitwarden.desktop", "com.apple.keychainaccess", "com.apple.Passwords",
        "org.keepassxc.keepassxc", "com.lastpass.LastPass", "in.sinew.Enpass-Desktop",
        "com.dashlane.dashlanephonefinal",
    ]

    /// Предел текста: длиннее — обрезается, чтобы индекс не раздувался.
    static let maxTextLength = 20_000
    /// Предел PNG: больше — картинку не запоминаем.
    static let maxImageBytes = 6 * 1024 * 1024
    static let defaultLimit = 500
    static let limits = [100, 250, 500, 1000]

    static func shouldSkip(types: [String]) -> Bool {
        types.contains { skippedTypes.contains($0) }
    }

    /// Одна строка с http(s)/ftp/mailto и хостом — ссылка; всё остальное — обычный текст.
    static func isLink(_ text: String) -> Bool {
        let t = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !t.isEmpty, t.count < 2048, !t.contains(where: { $0.isWhitespace }),
              let url = URL(string: t), let scheme = url.scheme?.lowercased() else { return false }
        if scheme == "mailto" { return true }
        return ["http", "https", "ftp"].contains(scheme) && (url.host?.isEmpty == false)
    }
}
